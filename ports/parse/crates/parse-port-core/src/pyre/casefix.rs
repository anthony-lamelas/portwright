/// `fixes[lo]`, if present.
pub fn extra_cases(lo: u32) -> Option<&'static [u32]> {
    EXTRA_CASES
        .binary_search_by_key(&lo, |&(k, _)| k)
        .ok()
        .and_then(|i| EXTRA_CASES.get(i))
        .map(|&(_, v)| v)
}
