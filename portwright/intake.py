"""Files a library's build writes into the package, recreated at intake.

Intake copies the package as it is in the clone. A file the build generates, such as
the ``version.py`` that setuptools-scm writes, isn't there, so the copy can't import:
isodate's ``__init__.py`` imports ``isodate/version.py``, and every test failed (open
item S). Building a wheel would run the library's own build code on the host, with
network, so intake instead reads the build configuration and writes the file the way
the tool would, with the version taken from the clone's git history.

Covered: setuptools-scm's ``write_to`` and ``version_file`` in ``[tool.setuptools_scm]``,
and hatch-vcs's ``version-file`` in ``[tool.hatch.build.hooks.vcs]``. A file that
already exists in the copy is left as it is.
"""

from __future__ import annotations

import re
import subprocess
import tomllib
from pathlib import Path

# setuptools-scm's template for .py files, without its typing preamble.
PY_TEMPLATE = """# file generated by setuptools-scm
# don't change, don't track in version control
# (written by Portwright's intake, as the build would)

__all__ = ["__version__", "__version_tuple__", "version", "version_tuple"]

__version__ = version = {version!r}
__version_tuple__ = version_tuple = {version_tuple!r}
"""
TEXT_TEMPLATE = "{version}\n"


def _git(source: Path, *args: str) -> str | None:
    done = subprocess.run(["git", "-C", str(source), *args], capture_output=True, text=True, check=False)
    return done.stdout.strip() if done.returncode == 0 else None


def scm_version(source: str | Path, fallback: str | None = None) -> str:
    """The version setuptools-scm's default scheme gives the clone's HEAD.

    A tagged commit gives its tag (``v0.7.2`` -> ``0.7.2``). Otherwise the next
    patch release as a development version, ``0.7.3.dev4+gabc1234``; with no tag at all,
    ``0.1.dev<commits>+g<hash>``. A clone with uncommitted changes isn't marked dirty:
    intake copies the files as they are, whatever git says.
    """
    source = Path(source)
    head = _git(source, "rev-parse", "--short=7", "HEAD")
    if head is None:
        return fallback or "0.0.0"
    described = _git(source, "describe", "--tags", "--long", "--match", "*[0-9]*")
    if described:
        match = re.fullmatch(r"v?(?P<tag>.+)-(?P<distance>\d+)-g[0-9a-f]+", described)
        if match:
            tag, distance = match["tag"], int(match["distance"])
            if distance == 0:
                return tag
            parts = re.fullmatch(r"(\d+(?:\.\d+)*)(.*)", tag)
            if parts and not parts[2]:
                numbers = parts[1].split(".")
                numbers[-1] = str(int(numbers[-1]) + 1)
                return f"{'.'.join(numbers)}.dev{distance}+g{head}"
            return f"{tag}.post1.dev{distance}+g{head}"
    if fallback:
        return fallback
    count = _git(source, "rev-list", "--count", "HEAD") or "0"
    return f"0.1.dev{count}+g{head}"


def version_tuple(version: str) -> tuple:
    """setuptools-scm's tuple: numeric parts as ints, then the rest as strings."""
    public, _, local = version.partition("+")
    items: list = []
    for piece in public.split("."):
        items.append(int(piece) if piece.isdigit() else piece)
    if local:
        items.append(local)
    return tuple(items)


def _declared_files(source: Path) -> list[tuple[str, str | None, str | None]]:
    """(path, template, fallback version) for each version file the build config names."""
    pyproject = source / "pyproject.toml"
    if not pyproject.is_file():
        return []
    try:
        config = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    except (tomllib.TOMLDecodeError, UnicodeDecodeError):
        return []
    tool = config.get("tool", {})
    found = []
    scm = tool.get("setuptools_scm")
    if isinstance(scm, dict):
        for key, template_key in (("write_to", "write_to_template"), ("version_file", "version_file_template")):
            if isinstance(scm.get(key), str):
                found.append((scm[key], scm.get(template_key), scm.get("fallback_version")))
    vcs = tool.get("hatch", {}).get("build", {}).get("hooks", {}).get("vcs", {})
    if isinstance(vcs, dict) and isinstance(vcs.get("version-file"), str):
        found.append((vcs["version-file"], vcs.get("template"), None))
    return found


def write_build_time_files(source: str | Path, package_path: str, destination: str | Path) -> list[str]:
    """Write version files the build would generate into the copied package.

    ``destination`` is where intake copied ``package_path``. Returns the paths written,
    relative to the clone, for the log and the report.
    """
    source = Path(source).resolve()
    destination = Path(destination)
    package = Path(package_path)
    written = []
    for relative, template, fallback in _declared_files(source):
        target = Path(relative)
        try:
            inside = target.relative_to(package)
        except ValueError:
            continue  # outside the copied package, so nothing imports it from the copy
        path = destination / inside
        if path.exists() or ".." in inside.parts:
            continue
        version = scm_version(source, fallback)
        default = PY_TEMPLATE if target.suffix == ".py" else TEXT_TEMPLATE
        text = (template or default).format(version=version, version_tuple=version_tuple(version), scm_version=None)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(str(target))
    return written
